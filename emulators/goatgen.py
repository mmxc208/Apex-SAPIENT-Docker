"""Generate the two router files, the certificates and the env file of the goat host tier.

    goatgen.py <registry.toml> <out_dir> [--frozen-routers]

The registry (see slots.py) describes a pod router and the host's fabric router. For each
router this writes router-<name>.json5 (an access list that follows goat's rules), a CA and
the certificates under pki/<name>/, and one goat1.env with the slot identities.

The router files depend on the pool, not on the aliases: every slot of the pool has its rules
from the start, so giving an alias a free slot only adds a certificate. --frozen-routers makes
that a promise: if an existing router file would change, nothing is written and the exit code is 3.

The access list text has a fixed form, because goat's checker (third_party/goat/acl-evaluate.py)
reads it with regular expressions, not a JSON5 parser: blocks in the order rules, subjects,
policies; each rule and subject starts with `id: "<id>",` and ends with `},`; a policy is
`{ rules: [...], subjects: [...] },`; comments only on their own lines.

Standard library only: this module also runs with the Mac's python3.
"""
import argparse
import importlib.util
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from slots import RegistryError, Router, load_registry

CA_DAYS = 3650
LEAF_DAYS = 825
_ALWAYS_RESERVED = {"ca", "router"}          # fixed certificate files of every router
_POD_RESERVED = {"fusion", "recorder", "bridge"}  # fixed certificate files of a pod router
_ALIAS = re.compile(r"[a-z0-9-]+")
_FABRIC_READ = ["declare_subscriber", "query", "declare_queryable", "reply",
                "declare_liveliness_subscriber", "liveliness_query"]
_DELIVER = ["put", "delete", "liveliness_token"]
_EGRESS_ALL = ["put", "delete", "query", "reply", "declare_subscriber", "declare_queryable",
               "liveliness_token", "liveliness_query", "declare_liveliness_subscriber"]


def _list(items) -> str:
    return "[" + ", ".join(json.dumps(item) for item in items) + "]"


def _rule(rid, messages, flows, key_exprs, permission="allow") -> str:
    return (
        "      {\n"
        f'        id: "{rid}",\n'
        f"        messages: {_list(messages)},\n"
        f"        flows: {_list(flows)},\n"
        f'        permission: "{permission}",\n'
        f"        key_exprs: {_list(key_exprs)},\n"
        "      },\n"
    )


def _subject(sid, **fields) -> str:
    inner = "".join(f" {name}: {_list(values)}," for name, values in fields.items())
    return f'      {{ id: "{sid}",{inner} }},\n'


def _policy(rules, subjects) -> str:
    return f"      {{ rules: {_list(rules)}, subjects: {_list(subjects)}, }},\n"


def _file(header: str, extra: str, rules: list, subjects: list, policies: list) -> str:
    return (
        f"{header}"
        "{\n"
        '  mode: "router",\n'
        "  listen: {\n"
        '    endpoints: ["tls/0.0.0.0:7447"],\n'
        "  },\n"
        "  scouting: {\n"
        "    multicast: { enabled: false },\n"
        "    gossip: { enabled: false },\n"
        "  },\n"
        f"{extra}"
        "  access_control: {\n"
        "    enabled: true,\n"
        '    default_permission: "deny",\n'
        "    rules: [\n" + "".join(rules) + "    ],\n"
        "    subjects: [\n" + "".join(subjects) + "    ],\n"
        "    policies: [\n" + "".join(policies) + "    ],\n"
        "  },\n"
        "}\n"
    )


def _transport(pod: bool) -> str:
    """The TLS settings; a pod router also drops a silent link after 5 s and on certificate expiry."""
    lease = "      tx: {\n        lease: 5000,\n      },\n" if pod else ""
    expiry = "        close_link_on_expiration: true,\n" if pod else ""
    return (
        "  transport: {\n"
        "    link: {\n"
        f"{lease}"
        "      tls: {\n"
        '        root_ca_certificate: "/certs/ca.pem",\n'
        '        listen_private_key: "/certs/router.key",\n'
        '        listen_certificate: "/certs/router.pem",\n'
        "        enable_mtls: true,\n"
        f"{expiry}"
        "      },\n"
        "    },\n"
        "  },\n"
    )


def render_fabric_router(router: Router) -> str:
    """The whole JSON5 file of a fabric router. Every slot of the pool gets a write rule."""
    anchors = [router.slot_id(k) for k in range(router.pool_size)]
    rules = [
        _rule("peer-r-scoped", _FABRIC_READ, ["egress", "ingress"], ["*/**", "**/@adv/**"]),
        _rule("peer-deliver-scoped", _DELIVER, ["egress"], ["*/**", "**/@adv/**"]),
    ]
    subjects = [_subject("mtls-peer", link_protocols=["tls"])]
    policies = [_policy(["peer-r-scoped", "peer-deliver-scoped"], ["mtls-peer"])]
    for p in anchors:
        rules.append(_rule(f"slot-w-{p}", _DELIVER, ["ingress"], [f"{p}/**", f"volatile/{p}/**", f"{p}/**/@adv/**"]))
        subjects.append(_subject(f"slot-{p}", cert_common_names=[p]))
        policies.append(_policy([f"slot-w-{p}"], [f"slot-{p}"]))
    header = (
        "// Generated by emulators/goatgen.py from goat1/registry.toml. Do not edit.\n"
        f"// Fabric router {router.router_cn}: mutual TLS only, access control by certificate common name.\n"
        "// A slot may write only under its own anchor; every mTLS peer may read and be delivered to in its scope.\n"
    )
    return _file(header, _transport(False), rules, subjects, policies)


def render_pod_router(router: Router) -> str:
    """The whole JSON5 file of a pod router. Every slot of the pool gets a write and a read rule."""
    x, f = router.prefix, router.fusion_node_id
    nodes = [router.slot_id(k) for k in range(router.pool_size)]
    rules = [
        _rule("fusion-down", ["put"], ["ingress"], [f"{x}sapient/v2/*/down/**", f"{x}fusion/up/**"]),
        _rule("fusion-own-up", ["put", "liveliness_token"], ["ingress"],
              [f"{x}sapient/v2/{f}/up/**", f"{x}sapient/v2/live/{f}"]),
        _rule("read-all", ["declare_subscriber", "query", "liveliness_query", "declare_liveliness_subscriber"],
              ["ingress"], [f"{x}**"]),
        _rule("bridge-r", ["declare_subscriber"], ["ingress"], [f"{x}fusion/up/**"]),
        _rule("bridge-w", ["put"], ["ingress"], [f"{x}fusion/down/**"]),
    ]
    subjects = [
        _subject("fusion", cert_common_names=[router.fusion_cn]),
        _subject("recorder", cert_common_names=[router.recorder_cn]),
        _subject("bridge", cert_common_names=[router.bridge_cn]),
    ]
    policies = [
        _policy(["fusion-down", "fusion-own-up"], ["fusion"]),
        _policy(["read-all"], ["fusion", "recorder"]),
        _policy(["bridge-r", "bridge-w"], ["bridge"]),
    ]
    for n in nodes:
        rules.append(_rule(f"slot-w-{n}", ["put", "liveliness_token"], ["ingress"],
                           [f"{x}sapient/v2/{n}/up/**", f"{x}sapient/v2/live/{n}"]))
    for n in nodes:
        rules.append(_rule(f"slot-r-{n}", ["declare_subscriber"], ["ingress"], [f"{x}sapient/v2/{n}/down/**"]))
    for n in nodes:
        subjects.append(_subject(f"slot-{n}", cert_common_names=[n]))
        policies.append(_policy([f"slot-w-{n}", f"slot-r-{n}"], [f"slot-{n}"]))
    # With default_permission "deny", zenohd also filters egress, so leaving it allowed takes a rule.
    rules.append(_rule("egress-all", _EGRESS_ALL, ["egress"], [f"{x}**"]))
    everyone = ["fusion", "recorder", "bridge"] + [f"slot-{n}" for n in nodes]
    policies.append(_policy(["egress-all"], everyone))
    header = (
        "// Generated by emulators/goatgen.py from goat1/registry.toml. Do not edit.\n"
        f"// Pod router {router.router_cn}: mutual TLS only, access control by certificate common name.\n"
        "// A slot may publish only as its own node and listen only to its own down keys.\n"
    )
    extra = (
        "  adminspace: {\n"
        "    enabled: true,\n"
        "    permissions: { read: true, write: false },\n"
        "  },\n"
    )
    return _file(header, extra + _transport(True), rules, subjects, policies)


def _env_name(*parts: str) -> str:
    return "_".join(parts).upper().replace("-", "_")


def env_lines(routers: dict[str, Router]) -> list[str]:
    lines = []
    for name, router in routers.items():
        for alias in router.slots:
            lines.append(f"{_env_name(name, alias)}_ID={router.alias_id(alias)}")
        if router.kind == "pod":
            lines.append(f"{_env_name(name)}_FUSION_NODE_ID={router.fusion_node_id}")
    return lines


# ---------------------------------------------------------------------------
# certificates (openssl through subprocess)
# ---------------------------------------------------------------------------
def _openssl(*args, stdin=None) -> subprocess.CompletedProcess:
    return subprocess.run(["openssl", *args], capture_output=True, text=True, input=stdin)


def _run(*args) -> None:
    result = _openssl(*args)
    if result.returncode != 0:
        raise RuntimeError(f"openssl {' '.join(args[:2])} failed: {result.stderr.strip()}")


def _subject_cn(pem: Path) -> str:
    out = _openssl("x509", "-noout", "-subject", "-nameopt", "RFC2253", "-in", str(pem)).stdout.strip()
    match = re.search(r"CN=([^,\s]+)", out)
    return match.group(1) if match else ""


def _public_key(args: list[str]) -> str:
    return _openssl(*args).stdout


def _ca_ok(directory: Path) -> bool:
    ca, key = directory / "ca.pem", directory / "ca.key"
    return (ca.is_file() and key.is_file()
            and _openssl("x509", "-checkend", "86400", "-noout", "-in", str(ca)).returncode == 0)


def _leaf_ok(directory: Path, name: str, cn: str) -> bool:
    """A kept certificate verifies against the CA, has the wanted common name and matches its key."""
    pem, key = directory / f"{name}.pem", directory / f"{name}.key"
    if not (pem.is_file() and key.is_file()):
        return False
    if _openssl("verify", "-CAfile", str(directory / "ca.pem"), str(pem)).returncode != 0:
        return False
    if _subject_cn(pem) != cn:
        return False
    cert_pub = _public_key(["x509", "-noout", "-pubkey", "-in", str(pem)])
    return bool(cert_pub) and cert_pub == _public_key(["pkey", "-pubout", "-in", str(key)])


def _new_key(path: Path) -> None:
    _run("genrsa", "-out", str(path), "2048")
    path.chmod(0o600)


def _make_ca(directory: Path, name: str, work: Path) -> None:
    key = directory / "ca.key"
    _new_key(key)
    cnf = work / "ca.cnf"
    cnf.write_text(
        "[req]\ndistinguished_name = dn\nprompt = no\nx509_extensions = v3\n"
        f"[dn]\nCN = goat1-{name}-ca\n"
        "[v3]\nbasicConstraints = critical, CA:TRUE\nkeyUsage = critical, keyCertSign, cRLSign\n"
        "subjectKeyIdentifier = hash\n")
    _run("req", "-x509", "-new", "-sha256", "-days", str(CA_DAYS), "-key", str(key),
         "-config", str(cnf), "-out", str(directory / "ca.pem"))


def _make_leaf(directory: Path, name: str, cn: str, work: Path) -> None:
    key, pem = directory / f"{name}.key", directory / f"{name}.pem"
    cnf = work / f"{name}.cnf"
    cnf.write_text(
        f"[req]\ndistinguished_name = dn\nprompt = no\n[dn]\nCN = {cn}\n"
        "[v3]\nbasicConstraints = critical, CA:FALSE\nkeyUsage = critical, digitalSignature, keyEncipherment\n"
        f"extendedKeyUsage = serverAuth, clientAuth\nsubjectAltName = DNS:{cn}\n"
        "subjectKeyIdentifier = hash\nauthorityKeyIdentifier = keyid\n")
    _new_key(key)
    csr = work / f"{name}.csr"
    _run("req", "-new", "-sha256", "-key", str(key), "-config", str(cnf), "-out", str(csr))
    _run("x509", "-req", "-sha256", "-days", str(LEAF_DAYS), "-in", str(csr),
         "-CA", str(directory / "ca.pem"), "-CAkey", str(directory / "ca.key"),
         "-set_serial", "0x" + _openssl("rand", "-hex", "16").stdout.strip(),
         "-extfile", str(cnf), "-extensions", "v3", "-out", str(pem))


def _identities(router: Router) -> dict[str, str]:
    """file name (without extension) -> certificate common name."""
    ids = {"router": router.router_cn}
    if router.kind == "pod":
        ids.update(fusion=router.fusion_cn, recorder=router.recorder_cn, bridge=router.bridge_cn)
    for alias in router.slots:
        ids[alias] = router.alias_id(alias)
    return ids


def _issue(router: Router, pki: Path) -> None:
    directory = pki / router.name
    directory.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=directory) as scratch:
        work = Path(scratch)
        if not _ca_ok(directory):
            _make_ca(directory, router.name, work)
        for name, cn in _identities(router).items():
            if not _leaf_ok(directory, name, cn):
                _make_leaf(directory, name, cn, work)


