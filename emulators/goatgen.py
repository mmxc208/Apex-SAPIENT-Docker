def _load_checker():
    path = Path(__file__).resolve().parent / "third_party" / "goat" / "acl-evaluate.py"
    spec = importlib.util.spec_from_file_location("acl_evaluate", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _check(name: str, text: str) -> None:
    """Fail when goat's checker cannot read every block of the rendered file, or finds a key it would refuse."""
    acl = _load_checker().Acl(text)
    ids = len(re.findall(r'^\s+(?:\{ )?id: "', text, flags=re.M))
    policies = text.count("rules: [") - 1
    if (len(acl.rules) + len(acl.subjects) != ids or len(acl.policies) != policies or not acl.rules
            or acl.unusable_key_exprs()):
        raise RegistryError(f"[{name}] the rendered access list is not in the form goat's checker reads")


def _render(routers: dict[str, Router]) -> dict[str, str]:
    files = {}
    for name, router in routers.items():
        text = render_fabric_router(router) if router.kind == "fabric" else render_pod_router(router)
        _check(name, text)
        files[f"router-{name}.json5"] = text
    return files


def _validate(routers: dict[str, Router]) -> None:
    """Aliases become file names under pki/<router>/, so they must be plain and must not hit a fixed file."""
    if not routers:
        raise RegistryError("the registry has no router")
    for name, router in routers.items():
        reserved = _ALWAYS_RESERVED | (_POD_RESERVED if router.kind == "pod" else set())
        for alias in router.slots:
            if not _ALIAS.fullmatch(alias):
                raise RegistryError(f"[{name}.slots] alias {alias!r} must match [a-z0-9-]+ (it is a file name)")
            if alias in reserved:
                raise RegistryError(f"[{name}.slots] alias {alias!r} is a reserved certificate name")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="goatgen.py", description=__doc__.split("\n\n")[0])
    parser.add_argument("registry")
    parser.add_argument("out_dir")
    parser.add_argument("--frozen-routers", action="store_true",
                        help="exit 3 and write nothing if an existing router file would change")
    args = parser.parse_args(argv)
    out = Path(args.out_dir)
    try:
        routers = load_registry(args.registry)
        _validate(routers)
        files = _render(routers)
        env = "\n".join(env_lines(routers)) + "\n"
    except (RegistryError, OSError) as exc:
        print(f"goatgen: {exc}", file=sys.stderr)
        return 2
    if shutil.which("openssl") is None:
        print("goatgen: openssl is not installed", file=sys.stderr)
        return 2
    if args.frozen_routers:
        changed = [n for n, text in files.items() if (out / n).is_file() and (out / n).read_text() != text]
        if changed:
            print("goatgen: --frozen-routers: would change " + ", ".join(changed)
                  + " (the pool, the prefix or an identity changed); nothing written", file=sys.stderr)
            return 3
    out.mkdir(parents=True, exist_ok=True)
    try:
        for router in routers.values():
            _issue(router, out / "pki")
    except RuntimeError as exc:
        print(f"goatgen: {exc}", file=sys.stderr)
        return 2
    for name, text in files.items():
        (out / name).write_text(text)
    (out / "goat1.env").write_text(env)
    if args.frozen_routers:
        print("router files unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
